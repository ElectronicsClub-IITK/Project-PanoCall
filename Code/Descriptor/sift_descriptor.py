# =====================================================
# GRADIENT PYRAMID
# =====================================================
#
# Purpose:
# Compute gradient magnitude and orientation
# for every Gaussian image.
#
# Output:
#
# mag_pyr[octave][scale]
# ori_pyr[octave][scale]
#
# =====================================================

def build_gradient_pyramid(
    gaussian_pyramid
):

    mag_pyr = []

    ori_pyr = []

    for octave in gaussian_pyramid:

        octave_mag = []
        octave_ori = []

        for img in octave:

            # Sobel gradients
            dx = cv2.Sobel(
                img,
                cv2.CV_32F,
                1,
                0,
                ksize=3
            )

            dy = cv2.Sobel(
                img,
                cv2.CV_32F,
                0,
                1,
                ksize=3
            )

            # Gradient magnitude
            magnitude = np.sqrt(
                dx**2 + dy**2
            )

            # Gradient orientation
            orientation = (
                np.degrees(
                    np.arctan2(
                        dy,
                        dx
                    )
                )
#                 % 360
            )

            octave_mag.append(
                magnitude
            )

            octave_ori.append(
                orientation
            )

        mag_pyr.append(
            octave_mag
        )

        ori_pyr.append(
            octave_ori
        )

    return mag_pyr, ori_pyr

