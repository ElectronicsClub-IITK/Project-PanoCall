# =====================================================
# GAUSSIAN PYRAMID
# =====================================================
#
# Purpose:
# Create multiple blurred versions of the image
# at different scales.
#
# Output:
# pyramid[octave][scale]
#
# Example:
#
# Octave 0:
#   sigma = 1.6
#   sigma = 2.0
#   sigma = 2.52
#   ...
#
# Octave 1:
#   same sigmas but on half-sized image
#
# =====================================================

def build_gaussian_pyramid(
    img,
    num_octaves=NUM_OCTAVES,
    sigmas=SIGMAS
):

    # store all octaves
    pyramid = []

    # convert image to float
    current = img.astype(
        np.float32
    )

    # build each octave
    for octave in range(
        num_octaves
    ):

        octave_images = []

        # create blurred images
        for sigma in sigmas:

            blurred = cv2.GaussianBlur(
                current,
                (0, 0),
                sigma
            )

            octave_images.append(
                blurred
            )

        # save current octave
        pyramid.append(
            octave_images
        )

        # downsample image by factor 2
        current = cv2.resize(
            current,
            (
                current.shape[1] // 2,
                current.shape[0] // 2
            ),
            interpolation=cv2.INTER_AREA
        )

    return pyramid

