# =====================================================
# CONTRAST FILTER
# =====================================================
#
# Remove weak extrema.
#
# =====================================================

def contrast_filter(
    extrema,
    dog_pyramid,
    threshold=1.0
):

    filtered = []

    for x, y, octave, scale in extrema:

        value = abs(
            dog_pyramid[octave][scale][y, x]
        )

        if value > threshold:

            filtered.append(
                (
                    x,
                    y,
                    octave,
                    scale
                )
            )

    return filtered

