# =====================================================
# TRILINEAR SIFT DESCRIPTOR
# =====================================================
#
# Output:
# 128 dimensional descriptor
#
# 4 x 4 spatial cells
# 8 orientation bins
#
# =====================================================

def generate_descriptors(
    oriented_keypoints,
    mag_pyr,
    ori_pyr
):

    descriptors = []
    valid_keypoints = []

    for x, y, octave, scale, kp_angle in oriented_keypoints:

        mag = mag_pyr[octave][scale]
        ori = ori_pyr[octave][scale]

        h, w = mag.shape

        descriptor = np.zeros(
            (4,4,8),
            dtype=np.float32
        )

        # 16x16 descriptor window
        radius = 8

        angle_rad = np.deg2rad(
            kp_angle
        )

        cos_t = np.cos(
            angle_rad
        )

        sin_t = np.sin(
            angle_rad
        )

        for dy in range(
            -radius,
            radius
        ):

            for dx in range(
                -radius,
                radius
            ):

                yy = y + dy
                xx = x + dx

                if (
                    yy < 0
                    or yy >= h
                    or xx < 0
                    or xx >= w
                ):
                    continue

                # ----------------------------------
                # Rotate coordinates into keypoint frame
                # ----------------------------------

                x_rot = (
                    cos_t * dx
                    +
                    sin_t * dy
                )

                y_rot = (
                    -sin_t * dx
                    +
                    cos_t * dy
                )

                # ----------------------------------
                # Convert to descriptor coordinates
                # ----------------------------------

                col_bin = (
                    x_rot / 4.0
                ) + 1.5

                row_bin = (
                    y_rot / 4.0
                ) + 1.5

                if (
                    row_bin < 0
                    or row_bin >= 4
                    or col_bin < 0
                    or col_bin >= 4
                ):
                    continue

                # ----------------------------------
                # Relative orientation
                # ----------------------------------

                angle = (
                    ori[yy,xx]
                    -
                    kp_angle
                ) % 360

                ori_bin = (
                    angle / 45.0
                )

                magnitude = mag[
                    yy,
                    xx
                ]

                # ----------------------------------
                # Row interpolation
                # ----------------------------------

                r0 = int(
                    np.floor(row_bin)
                )

                r1 = r0 + 1

                wr1 = (
                    row_bin - r0
                )

                wr0 = (
                    1 - wr1
                )

                # ----------------------------------
                # Column interpolation
                # ----------------------------------

                c0 = int(
                    np.floor(col_bin)
                )

                c1 = c0 + 1

                wc1 = (
                    col_bin - c0
                )

                wc0 = (
                    1 - wc1
                )

                # ----------------------------------
                # Orientation interpolation
                # ----------------------------------

                o0 = int(
                    np.floor(ori_bin)
                ) % 8

                o1 = (
                    o0 + 1
                ) % 8

                wo1 = (
                    ori_bin
                    -
                    np.floor(
                        ori_bin
                    )
                )

                wo0 = (
                    1 - wo1
                )

                # ----------------------------------
                # Trilinear interpolation
                # ----------------------------------

                for r, wr in [
                    (r0,wr0),
                    (r1,wr1)
                ]:

                    if not (
                        0 <= r < 4
                    ):
                        continue

                    for c, wc in [
                        (c0,wc0),
                        (c1,wc1)
                    ]:

                        if not (
                            0 <= c < 4
                        ):
                            continue

                        descriptor[
                            r,
                            c,
                            o0
                        ] += (
                            magnitude
                            *
                            wr
                            *
                            wc
                            *
                            wo0
                        )

                        descriptor[
                            r,
                            c,
                            o1
                        ] += (
                            magnitude
                            *
                            wr
                            *
                            wc
                            *
                            wo1
                        )

        # ----------------------------------
        # Flatten
        # ----------------------------------

        descriptor = descriptor.flatten()

        # ----------------------------------
        # Normalize
        # ----------------------------------

        norm = np.linalg.norm(
            descriptor
        )

        if norm > 1e-7:

            descriptor /= norm

            descriptor = np.clip(
                descriptor,
                0,
                0.2
            )

            descriptor /= (
                np.linalg.norm(
                    descriptor
                )
                +
                1e-7
            )

        descriptors.append(
            descriptor
        )

        valid_keypoints.append(
            (
                x,
                y,
                octave,
                scale,
                kp_angle
            )
        )

    return (
        valid_keypoints,
        np.array(descriptors)
    )

