# =====================================================
# NON MAXIMUM SUPPRESSION
# =====================================================

def nms_filter(
    keypoints,
    dog_pyramid,
    radius=5
):

    scored = []

    for x, y, octave, scale in keypoints:

        response = abs(
            dog_pyramid[octave][scale][y, x]
        )

        scored.append(
            (
                response,
                x,
                y,
                octave,
                scale
            )
        )

    scored.sort(
        reverse=True
    )

    selected = []

    for response, x, y, octave, scale in scored:

        keep = True

        for _, sx, sy, so, ss in selected:

            if octave != so:
                continue

            dist = np.sqrt(
                (x - sx)**2
                +
                (y - sy)**2
            )

            if dist < radius:

                keep = False
                break

        if keep:

            selected.append(
                (
                    response,
                    x,
                    y,
                    octave,
                    scale
                )
            )

    result = []

    for _, x, y, octave, scale in selected:

        result.append(
            (
                x,
                y,
                octave,
                scale
            )
        )

    return result

