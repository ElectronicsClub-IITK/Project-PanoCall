# =====================================================
# SCALE SPACE EXTREMA DETECTION
# =====================================================
#
# Purpose:
# Find maxima and minima in scale-space.
#
# Output:
#
# (x, y, octave, scale)
#
# =====================================================

def detect_extrema(
    dog_pyramid
):

    keypoints = []

    for octave_idx in range(
        len(dog_pyramid)
    ):

        octave = dog_pyramid[
            octave_idx
        ]

        # skip first and last scale
        for scale_idx in range(
            1,
            len(octave)-1
        ):

            prev_img = octave[
                scale_idx-1
            ]

            curr_img = octave[
                scale_idx
            ]

            next_img = octave[
                scale_idx+1
            ]

            h, w = curr_img.shape

            for y in range(
                1,
                h-1
            ):

                for x in range(
                    1,
                    w-1
                ):

                    value = curr_img[
                        y,
                        x
                    ]

                    neighbors = []

                    # previous scale
                    neighbors.extend(
                        prev_img[
                            y-1:y+2,
                            x-1:x+2
                        ].flatten()
                    )

                    # current scale
                    neighbors.extend(
                        curr_img[
                            y-1:y+2,
                            x-1:x+2
                        ].flatten()
                    )

                    # next scale
                    neighbors.extend(
                        next_img[
                            y-1:y+2,
                            x-1:x+2
                        ].flatten()
                    )

                    neighbors.remove(
                        value
                    )

                    if (
                        value > max(neighbors)
                        or
                        value < min(neighbors)
                    ):

                        keypoints.append(
                            (
                                x,
                                y,
                                octave_idx,
                                scale_idx
                            )
                        )

    return keypoints

