# =====================================================
# DIFFERENCE OF GAUSSIAN PYRAMID
# =====================================================
#
# Purpose:
# Approximate the Laplacian of Gaussian.
#
# Output:
# dog_pyr[octave][dog_level]
#
# =====================================================

def build_dog_pyramid(
    gaussian_pyramid
):

    dog_pyramid = []

    for octave in gaussian_pyramid:

        dog_octave = []

        for i in range(
            len(octave) - 1
        ):

            dog = (
                octave[i + 1]
                -
                octave[i]
            )

            dog_octave.append(
                dog
            )

        dog_pyramid.append(
            dog_octave
        )

    return dog_pyramid

