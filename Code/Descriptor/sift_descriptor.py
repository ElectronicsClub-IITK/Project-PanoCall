# =====================================================
# EDGE FILTER
# =====================================================
#
# Remove edge responses using Hessian matrix.
#
# =====================================================

def edge_filter(
    keypoints,
    dog_pyramid,
    r=10
):

    filtered = []

    for x, y, octave, scale in keypoints:

        img = dog_pyramid[octave][scale]

        if (
            x < 1
            or y < 1
            or x >= img.shape[1]-1
            or y >= img.shape[0]-1
        ):
            continue

        Dxx = (
            img[y, x+1]
            +
            img[y, x-1]
            -
            2 * img[y, x]
        )

        Dyy = (
            img[y+1, x]
            +
            img[y-1, x]
            -
            2 * img[y, x]
        )

        Dxy = (
            img[y+1, x+1]
            -
            img[y+1, x-1]
            -
            img[y-1, x+1]
            +
            img[y-1, x-1]
        ) / 4.0

        trace = Dxx + Dyy

        det = (
            Dxx * Dyy
            -
            Dxy * Dxy
        )

        if det <= 0:
            continue

        ratio = (
            trace * trace
        ) / det

        threshold = (
            (r + 1) ** 2
        ) / r

        if ratio < threshold:

            filtered.append(
                (
                    x,
                    y,
                    octave,
                    scale
                )
            )

    return filtered

